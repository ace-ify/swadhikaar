  r           record;
  v_status    int;
  v_timedout  boolean;
  v_err       text;
  v_found     boolean;
  v_done      int := 0;
  v_requeue   int := 0;
  v_failed    int := 0;
  v_inflight  int := 0;
BEGIN
  FOR r IN
    SELECT id, attempts, started_at, dispatch_request_id
    FROM voice_calls
    WHERE status = 'in_progress'
    FOR UPDATE SKIP LOCKED
  LOOP
    v_status := NULL; v_timedout := NULL; v_err := NULL; v_found := false;

    IF r.dispatch_request_id IS NOT NULL THEN
      SELECT status_code, timed_out, error_msg, true
        INTO v_status, v_timedout, v_err, v_found
        FROM net._http_response
       WHERE id = r.dispatch_request_id;
    END IF;

    IF v_found AND v_status BETWEEN 200 AND 299 THEN
      UPDATE voice_calls
         SET status = 'completed', ended_at = COALESCE(ended_at, now()), last_error = NULL
       WHERE id = r.id;
      v_done := v_done + 1;

    ELSIF v_found AND v_status >= 400 THEN
      -- The function rejected the request, so no call was placed. Safe to retry.
      IF r.attempts < max_attempts THEN
        UPDATE voice_calls
           SET status = 'scheduled', attempts = attempts + 1, started_at = NULL,
               dispatch_request_id = NULL,
               last_error = 'dispatch returned HTTP ' || v_status || ' - requeued'
         WHERE id = r.id;
        v_requeue := v_requeue + 1;
      ELSE
        UPDATE voice_calls
           SET status = 'failed', attempts = attempts + 1,
               last_error = 'abandoned after ' || max_attempts
                            || ' attempts (last HTTP ' || v_status || ')'
         WHERE id = r.id;
        v_failed := v_failed + 1;
      END IF;

    ELSIF v_found AND COALESCE(v_timedout, false) THEN
      -- Deliberately terminal. The phone may have rung; do not call again.
      UPDATE voice_calls
         SET status = 'failed',
             last_error = 'dispatch timed out - outcome unknown, not retried to avoid a '
                          || 'duplicate call to the patient. Review manually. ('
                          || COALESCE(v_err, '') || ')'
       WHERE id = r.id;
      v_failed := v_failed + 1;

    ELSE
      -- No response recorded yet: still ringing, or pg_net pruned the row.
      IF r.started_at IS NULL OR r.started_at > now() - stale_after THEN
        v_inflight := v_inflight + 1;
      ELSE
        UPDATE voice_calls
           SET status = 'failed',
               last_error = 'no dispatch response recorded within ' || stale_after::text
                            || ' - outcome unknown, not retried'
         WHERE id = r.id;
        v_failed := v_failed + 1;
      END IF;
    END IF;
  END LOOP;

  RETURN QUERY SELECT v_done, v_requeue, v_failed, v_inflight;
END;
$function$;

