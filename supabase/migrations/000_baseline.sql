CREATE OR REPLACE FUNCTION public.visible_patient_ids()
 RETURNS SETOF uuid
 LANGUAGE sql
 STABLE SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
  SELECT p.id
  FROM patients p
  WHERE public.is_admin()
     OR (public.current_app_role() = 'doctor'
         AND p.assigned_doctor_id IN (SELECT d.id FROM doctors d WHERE d.auth_user_id = auth.uid()))
     OR (public.current_app_role() = 'asha'
         AND p.village IN (SELECT public.asha_villages()))
     OR p.auth_user_id = auth.uid();
$function$;

-- An ASHA-registered patient has no assigned_doctor_id, so visible_patient_ids()
-- hid their escalation from every doctor: the alert was written and read by nobody
-- but admin. Scoped to escalations only — widening visible_patient_ids() itself
-- would expose every unassigned patient's full record to every doctor.
CREATE OR REPLACE FUNCTION public.escalation_visible(p_patient_id uuid)
 RETURNS boolean
 LANGUAGE sql
 STABLE SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
  select
    p_patient_id in (select public.visible_patient_ids())
    or (
      public.current_app_role() = 'doctor'
      and exists (
        select 1 from patients p
        where p.id = p_patient_id and p.assigned_doctor_id is null
      )
    );
$function$;

