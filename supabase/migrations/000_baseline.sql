create or replace view public.district_occupational_health
  with (security_invoker = true) as
 SELECT p.district,
    p.village,
    p.occupation,
    p.crop_type,
    count(*) AS patients,
    count(*) FILTER (WHERE p.last_pesticide_exposure > (CURRENT_DATE - 30)) AS pesticide_exposed_30d,
    count(*) FILTER (WHERE p.risk_level = 'High'::text) AS high_risk,
    count(*) FILTER (WHERE s.breathlessness IS NOT NULL AND (lower(s.breathlessness) <> ALL (ARRAY['none'::text, 'no'::text, 'never'::text, ''::text]))) AS breathlessness,
    count(*) FILTER (WHERE s.chest_discomfort IS NOT NULL AND (lower(s.chest_discomfort) <> ALL (ARRAY['none'::text, 'no'::text, 'never'::text, ''::text]))) AS chest_discomfort,
    count(*) FILTER (WHERE s.dizziness_blackouts IS NOT NULL AND (lower(s.dizziness_blackouts) <> ALL (ARRAY['none'::text, 'no'::text, 'never'::text, ''::text]))) AS dizziness,
    count(*) FILTER (WHERE s.fatigue_weakness IS NOT NULL AND (lower(s.fatigue_weakness) <> ALL (ARRAY['none'::text, 'no'::text, 'never'::text, ''::text]))) AS fatigue
   FROM patients p
     LEFT JOIN LATERAL ( SELECT s2.chest_discomfort,
            s2.breathlessness,
            s2.fatigue_weakness,
            s2.dizziness_blackouts
           FROM symptoms s2
          WHERE s2.patient_id = p.id
          ORDER BY s2.recorded_at DESC NULLS LAST
         LIMIT 1) s ON true
  WHERE p.district IS NOT NULL
  GROUP BY p.district, p.village, p.occupation, p.crop_type;

