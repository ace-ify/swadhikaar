-- WHY THIS EXISTS
-- The live database had 21 applied migrations; only 5 files existed on disk. The
-- schema that built production was largely not in version control. Two concrete
-- dangers, both triggered by anyone running `supabase db reset`:
--
--   1. `user_roles` — the table every auth path depends on (is_admin(),
--      current_app_role(), the Next.js proxy, auth-context) — was created by NO
--      migration file. A rebuilt database had no roles table, so all
--      authorisation broke.
--   2. `001_initial_schema.sql` contained eight `admins_full_access` policies
--      reading `raw_user_meta_data->>'role'`. Users can write their own
--      user_metadata, so that is a self-promotion vector: any account could make
--      itself admin. Verified 0 such policies live (pg_policies), but a reset
--      would have recreated them.
--
-- This file reproduces the live `public` schema. It supersedes 001-005, which are
-- retained only as history and must not be run.
--
-- NOT INCLUDED, and must be recreated by hand:
--   * Vault secrets. The cron jobs at the end read secrets by name from
--     `vault.decrypted_secrets`; the secret VALUES are not here and never should be.
--     Recreate with: select vault.create_secret('<value>', '<name>');
--   * Seed/patient data. Use backend/seed_data.py.
--   * Supabase-managed schemas (auth, storage, realtime, graphql).
--
-- Generated by reading pg_catalog directly (`supabase db dump` is unavailable on
-- this project: the CLI cannot create its login role).
-- =============================================================================

