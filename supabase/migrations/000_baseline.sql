-- Called by the pg_cron job at the end of this file. Reads its credentials from
-- vault by name; the secret VALUES are not in this migration and must be created
-- separately (see the header).
CREATE OR REPLACE FUNCTION public.place_due_recovery_calls(batch_size integer DEFAULT 25)
 RETURNS integer
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public', 'extensions', 'net'
AS $function$
DECLARE
  v_url text;
  v_key text;
  v_req bigint;
  r     record;
  n     int := 0;
BEGIN
  SELECT decrypted_secret INTO v_url FROM vault.decrypted_secrets WHERE name = 'project_url';
  SELECT decrypted_secret INTO v_key FROM vault.decrypted_secrets WHERE name = 'edge_function_key';

  IF v_url IS NULL OR v_key IS NULL THEN
    RAISE NOTICE 'vault secrets project_url / edge_function_key not set - skipping';
    RETURN 0;
  END IF;

  FOR r IN
    SELECT vc.id, vc.patient_id, vc.language, vc.call_type,
           p.name AS patient_name, p.phone
    FROM voice_calls vc
    JOIN patients p ON p.id = vc.patient_id
    WHERE vc.status = 'scheduled'
      AND vc.scheduled_for IS NOT NULL
      AND vc.scheduled_for <= now()
      AND p.phone IS NOT NULL
    ORDER BY vc.scheduled_for
    LIMIT batch_size
    FOR UPDATE OF vc SKIP LOCKED
  LOOP
    -- 120s, not 5s: the function holds the connection open for the whole ring.
    SELECT net.http_post(
      url     := v_url || '/functions/v1/start-voice-call',
      headers := jsonb_build_object(
                   'Content-Type', 'application/json',
                   'Authorization', 'Bearer ' || v_key
                 ),
      body    := jsonb_build_object(
                   'patient_id',   r.patient_id,
                   'patient_name', r.patient_name,
                   'language',     r.language,
                   'call_type',    COALESCE(r.call_type, 'recovery'),
                   'phone_number', r.phone
                 ),
      timeout_milliseconds := 120000
    ) INTO v_req;

    UPDATE voice_calls
       SET status = 'in_progress',
           started_at = now(),
           dispatch_request_id = v_req
     WHERE id = r.id;

    n := n + 1;
  END LOOP;

  RETURN n;
END;
$function$;

